import type { CountryEntry } from "@/scripts/country-data-generator/cldr-data";

export function buildSharedCountriesFile(dataset: CountryEntry[]): string {
  const codeLines = dataset.map(entry => `  "${entry.code}",`).join("\n");
  const countryLines = dataset
    .map(
      entry =>
        `  ${entry.code}: { en: ${JSON.stringify(entry.en)}, ar: ${JSON.stringify(entry.ar)}, flag: ${JSON.stringify(entry.flag)} },`
    )
    .join("\n");

  return `// AUTO-GENERATED by scripts/country-data-generator — do not edit manually.
// Run \`bun run generate:countries\` to regenerate.

/** ISO 3166-1 alpha-2 codes, uppercase, curated subset (see generator). */
export const COUNTRY_CODES = [
${codeLines}
] as const;

/** Union of every valid ISO 3166-1 alpha-2 code in the committed dataset. */
export type CountryCode = (typeof COUNTRY_CODES)[number];

/** Per-code localized display name + flag emoji (regional-indicator derived). */
export const COUNTRIES: Record<CountryCode, { en: string; ar: string; flag: string }> = {
${countryLines}
};
`;
}
