-- =============================================================================
-- 11-users-country-code-backfill.sql
-- -----------------------------------------------------------------------------
-- Purpose: One-time, data-only backfill of `users.country_code` (ISO 3166-1
--          alpha-2) from the legacy free-text `users.country` display values
--          written before every country surface (register, admin create/edit,
--          broadcast audience) was bridged onto the canonical
--          (display name, ISO code) vocabulary (plan issue-230, deferred
--          item D-2).
--
-- Vocabulary parity: the seed-to-code bridge (`countrySeedToCode`,
-- shared/lib/country-code.ts) resolves a persisted display value through the
-- case-insensitive English-name index `COUNTRY_EN_NAME_INDEX` — built from
-- the generated dataset (`shared/constants/countries.ts`) with LAST-WINS
-- semantics on duplicate lowercased names. The VALUES list below is that
-- index inverted (canonical name per code; the dataset's English names are
-- unique — 255 rows), so a row stamped here resolves to exactly the same
-- code the bridge assigns on write.
--
-- Semantics:
--   - Match: `lower(btrim(country)) = lower(name)` — the bridge compares the
--     trimmed+lowercased seed against the lowercased name.
--   - Canonicalization: stamping the code also rewrites `country` to the
--     dataset's canonical English display name, upholding the write-path
--     invariant `countryCode non-null iff country IS the canonical dataset
--     display name` (e.g. "egypt" -> "Egypt").
--   - Free text that is NOT a dataset display name (custom user prose,
--     Arabic names — the bridge resolves English names only) keeps the
--     legacy shape untouched: raw text + NULL code.
--
-- Idempotency: the guard `country_code IS DISTINCT FROM code OR country IS
-- DISTINCT FROM name` makes a re-run a no-op — fully stamped rows match no
-- VALUES row's guard. The migration never writes to audit_logs.
--
-- SQLite: not applicable — `country_code` lives in the shared drizzle
-- schema, and custom data migrations are PostgreSQL-only
-- (applyCustomMigrations is skipped for the SQLite dialect).
-- =============================================================================

